#!/usr/bin/env bash
# find_ip.sh — نمایش آی‌پی داخلی و عمومی رزبری برای پورت‌فوروارد سریع
# اجرا روی Raspberry Pi:  bash find_ip.sh

echo "════════════════════════════════════════════════"
echo " IP داخلی رزبری (چیزی که در مودم فوروارد می‌کنی)"
echo "════════════════════════════════════════════════"
hostname -I 2>/dev/null | tr ' ' '\n' | grep -v '^$' | sed 's/^/   /'

echo
echo "════════════════════════════════════════════════"
echo " IP عمومی شرکت (آدرسی که در پنل می‌گذاری)"
echo "════════════════════════════════════════════════"
PUB=$(curl -s --max-time 8 https://api.ipify.org)
if [ -z "$PUB" ]; then PUB=$(curl -s --max-time 8 https://ifconfig.me); fi
echo "   $PUB"

echo
echo "════════════════════════════════════════════════"
echo " گیت‌وی (IP مودم شرکت)"
echo "════════════════════════════════════════════════"
ip route 2>/dev/null | grep default | sed 's/^/   /'

echo
echo "════════════════════════════════════════════════"
echo " بررسی CGNAT"
echo "════════════════════════════════════════════════"
case "$PUB" in
  100.6[4-9].*|100.[7-9][0-9].*|100.1[0-1][0-9].*|100.12[0-7].*)
    echo "   ⚠ IP عمومی در محدوده CGNAT است."
    echo "   پورت‌فوروارد کار نمی‌کند → باید از تونل (cloudflared/ngrok) استفاده کنی."
    ;;
  *)
    echo "   اگر IP بالا با WAN IP داخل پنل مودم یکی بود، پورت‌فوروارد کار می‌کند."
    echo "   اگر یکی نبود، ISP از CGNAT استفاده می‌کند و فوروارد بی‌فایده است."
    ;;
esac

echo
echo "   وضعیت سرور در (باید listen باشد):"
ss -tlnp 2>/dev/null | grep ':5000' | sed 's/^/   /' || echo "   سرور روی 5000 اجرا نیست"
echo "════════════════════════════════════════════════"
