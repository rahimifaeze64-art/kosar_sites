norm AS (
    SELECT rn, university, student_id, system_password, degree, field,
           translate(replace(regexp_replace(trim(name), '[[:space:]]+', ' ', 'g'), 'ـ', ''), 'أإآىيئةك', 'اااییهک') AS nname
    FROM src
    WHERE student_id <> '' OR system_password <> '' OR university <> '' OR degree IS NOT NULL OR field IS NOT NULL
),
dedup AS (
    SELECT DISTINCT ON (nname) * FROM norm ORDER BY nname, rn
),
-- شماره‌های دانشجویی که در فایل به بیش از یک نفر نسبت داده شده‌اند → نادیده گرفته می‌شوند
sid_dup AS (
    SELECT student_id FROM dedup WHERE student_id <> '' GROUP BY student_id HAVING count(*) > 1
),
safe AS (
    SELECT d.*, CASE WHEN d.student_id = '' OR EXISTS (SELECT 1 FROM sid_dup s WHERE s.student_id = d.student_id)
                              THEN '' ELSE d.student_id END AS sid_safe
    FROM dedup d
)
UPDATE public.profiles p SET
    university      = COALESCE(NULLIF(d.university, ''), p.university),
    student_id      = CASE
                          WHEN d.sid_safe = '' THEN p.student_id
                          WHEN EXISTS (SELECT 1 FROM public.profiles p2
                                       WHERE p2.student_id = d.sid_safe AND p2.id <> p.id)
                               THEN p.student_id
                          ELSE d.sid_safe
                      END,
    system_password = COALESCE(NULLIF(d.system_password, ''), p.system_password),
    field           = COALESCE(d.field, p.field),
    degree          = COALESCE(d.degree, p.degree),
    updated_at      = now()
FROM safe d
WHERE p.role = 'student'
  AND translate(replace(regexp_replace(trim(p.name), '[[:space:]]+', ' ', 'g'), 'ـ', ''), 'أإآىيئةك', 'اااییهک') = d.nname
  -- اگر چند پروفایل با همین نام وجود داشت، فقط یکی (مرجّح: همان که شماره را دارد) به‌روزرسانی شود
  AND p.id = (
      SELECT p3.id FROM public.profiles p3
      WHERE p3.role = 'student' AND translate(replace(regexp_replace(trim(p3.name), '[[:space:]]+', ' ', 'g'), 'ـ', ''), 'أإآىيئةك', 'اااییهک') = d.nname
      ORDER BY (p3.student_id IS NOT DISTINCT FROM d.sid_safe) DESC, p3.created_at NULLS LAST, p3.id
      LIMIT 1
  );

