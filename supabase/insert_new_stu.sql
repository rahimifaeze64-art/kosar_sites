    (305, 'علي حمزه جواد العجیلي')
)

, cleaned AS (
    SELECT seq,
           trim(regexp_replace(raw, '[[:space:]]+', ' ', 'g')) AS name
    FROM src
    WHERE trim(regexp_replace(raw, '[[:space:]]+', ' ', 'g')) <> ''
)

, norm AS (
    SELECT seq,
           name,
           translate(name, 'أإآىكيةـ', 'اااییه') AS nname
    FROM cleaned
)

, dedup AS (               -- حذف تکراری‌های داخل خود لیست
    SELECT seq, name, nname,
           ROW_NUMBER() OVER (PARTITION BY nname ORDER BY seq) AS rn
    FROM norm
)

, fresh AS (               -- ردِ نام‌های موجود در دیتابیس و یوزرنیم تکراری
    SELECT d.seq, d.name, d.nname
    FROM dedup d
    WHERE d.rn = 1
      AND d.name NOT IN ('انصرافی ها', 'تکمیل شده')      -- سرصفحهٔ لیست، نام نیست
      AND NOT EXISTS (
              SELECT 1
              FROM public.profiles p
              WHERE translate(
                        trim(regexp_replace(p.name, '[[:space:]]+', ' ', 'g')),
                        'أإآىكيةـ', 'اااییه'
                    ) = d.nname
          )
      AND NOT EXISTS (
              SELECT 1
              FROM public.profiles p2
              WHERE p2.username = 'stu' || lpad(d.seq::text, 3, '0')
          )
)

-- ── درج (نام تکراری → نادیده گرفته می‌شود) ──
INSERT INTO public.profiles
    (id, name, username, role, active, current_path, created_at)
SELECT
    'nstu-' || substr(md5(d.nname), 1, 10),
    d.name,
    'stu'   || lpad(d.seq::text, 3, '0'),
    'student',
    true,
    'studying',
    now()
FROM fresh d
ON CONFLICT (id) DO NOTHING;

